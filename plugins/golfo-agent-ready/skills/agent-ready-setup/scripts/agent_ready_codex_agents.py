"""Native Codex subagents: the .codex/agents/<name>.toml that each managed .agents/agents/<name>.md produces.

Codex reads one TOML file per custom agent from .codex/agents/, with ``name``, ``description`` and
``developer_instructions``. The TOML is derived from the Markdown subagent (its frontmatter gives the
name and the description, its body the instructions), so it is not a byte copy of a template: the plan
records the sha256 of the rendered text, and the Python and the Bash projections render it with this
same module (render-codex-agent.py), so both write the same bytes.
"""

import json
import os
import re

from agent_ready_common import ProfileError

# Directory of the subagent templates of a profile, and of the native Codex subagents of a project.
AGENTS_TEMPLATE_DIRECTORY = "agents"
CODEX_AGENTS_DIRECTORY = ".codex/agents"
CODEX_AGENT_SUFFIX = ".toml"
MARKDOWN_SUFFIX = ".md"
# Where a YAML comment starts after a plain scalar: a # preceded by whitespace.
YAML_COMMENT = re.compile(r"\s+#")
FRONTMATTER_FENCE = "---"
# Frontmatter keys Codex requires; the body becomes developer_instructions.
REQUIRED_FRONTMATTER_KEYS = ("name", "description")
# The table of the Codex features a subagent turns off, and the note of what Codex cannot enforce.
FEATURES_TABLE = "features"
LIMITATION_KEY = "limitation"
GENERATED_HEADER = "# Generated by agent-ready-setup from .agents/agents/{file}; edit that file, not this one.\n"
# Escapes of a TOML basic string that are not the character itself (TOML 1.0, section "String").
MULTILINE_ESCAPES = {"\\": "\\\\", "\b": "\\b", "\f": "\\f", "\r": "\\r"}


def is_subagent_template(relative_path):
    """True for a subagent of a profile tree: a Markdown file under agents/ (the agents/*.md of the Bash
    projections, whose * also matches a folder)."""
    return relative_path.startswith(AGENTS_TEMPLATE_DIRECTORY + "/") and relative_path.endswith(MARKDOWN_SUFFIX)


def codex_agent_destination(relative_path):
    """The .codex/agents/<name>.toml a subagent template produces."""
    name = os.path.basename(relative_path)[:-len(MARKDOWN_SUFFIX)]
    return f"{CODEX_AGENTS_DIRECTORY}/{name}{CODEX_AGENT_SUFFIX}"


def closing_quote_index(value):
    """Index of the quote that closes the quoted scalar ``value`` starts with, or -1 when it is not closed.

    In a 'single-quoted' scalar '' is a quote; in a "double-quoted" one a backslash escapes the next character.
    """
    quote = value[0]
    index = 1
    while index < len(value):
        character = value[index]
        if quote == '"' and character == "\\":
            index += 2
            continue
        if character == quote:
            if quote == "'" and value[index + 1:index + 2] == "'":
                index += 2
                continue
            return index
        index += 1
    return -1


def unquoted_scalar(value, key, origin):
    """The value of a one-line YAML scalar: plain, 'single-quoted' or "double-quoted", without a trailing # comment."""
    value = value.strip()
    if value[:1] in ("|", ">"):
        raise ProfileError(f"{origin}: the frontmatter key '{key}' must be a one-line string to become a Codex subagent")
    if value[:1] not in ("'", '"'):
        # A plain scalar ends where a comment starts: a # after whitespace.
        return YAML_COMMENT.split(value, 1)[0].strip()
    closing = closing_quote_index(value)
    rest = value[closing + 1:].strip() if closing > 0 else None
    if rest is None or (rest and not rest.startswith("#")):
        raise ProfileError(f"{origin}: the frontmatter key '{key}' is not a valid quoted string")
    if value[0] == "'":
        return value[1:closing].replace("''", "'")
    try:
        return json.loads(value[:closing + 1])
    except ValueError as caught_error:
        raise ProfileError(f"{origin}: the frontmatter key '{key}' is not a valid double-quoted string") from caught_error


def split_subagent(text, origin):
    """({key: value}, body) of a subagent template; ``origin`` names it in errors."""
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != FRONTMATTER_FENCE:
        raise ProfileError(f"{origin}: a subagent must start with a frontmatter (---) holding its name and description")
    try:
        closing = next(index for index in range(1, len(lines)) if lines[index].strip() == FRONTMATTER_FENCE)
    except StopIteration as caught_error:
        raise ProfileError(f"{origin}: the frontmatter of the subagent is not closed with ---") from caught_error
    fields = {}
    for line in lines[1:closing]:
        if not line or line[0] in (" ", "\t", "#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        if key.strip() in REQUIRED_FRONTMATTER_KEYS:
            fields[key.strip()] = unquoted_scalar(value, key.strip(), origin)
    missing = [key for key in REQUIRED_FRONTMATTER_KEYS if not fields.get(key)]
    if missing:
        raise ProfileError(f"{origin}: the subagent frontmatter has no {' or '.join(missing)}, which Codex requires")
    body = "\n".join(lines[closing + 1:]).strip("\n") + "\n"
    return fields, body


def toml_basic_string(value):
    """A one-line TOML basic string; JSON escapes are valid TOML escapes."""
    return json.dumps(value, ensure_ascii=False)


def escaped_character(character):
    """One character of a TOML multi-line basic string: line breaks and tabs stay, other controls are escaped."""
    if character in MULTILINE_ESCAPES:
        return MULTILINE_ESCAPES[character]
    if character in "\n\t":
        return character
    if ord(character) < 0x20 or ord(character) == 0x7F:
        return f"\\u{ord(character):04X}"
    return character


def toml_multiline_string(value):
    """A TOML multi-line basic string that holds ``value`` exactly, line breaks included."""
    escaped = "".join(escaped_character(character) for character in value)
    # Three quotes would close the string: the third one is escaped.
    escaped = escaped.replace('"""', '""\\"')
    if escaped.endswith('"'):
        escaped = escaped[:-1] + '\\"'
    # The line break right after the opening quotes is trimmed by TOML, so the value starts on the next line.
    return '"""\n' + escaped + '"""'


def toml_value(value):
    """A TOML value of the metadata mapping: a boolean, or a string."""
    if isinstance(value, bool):
        return "true" if value else "false"
    return toml_basic_string(str(value))


def metadata_lines(extra):
    """The top-level keys and the [features] table of the metadata of a subagent (agent_ready_agent_metadata)."""
    top = [f"{key} = {toml_value(value)}" for key, value in sorted(extra.items())
           if key not in (FEATURES_TABLE, LIMITATION_KEY)]
    features = extra.get(FEATURES_TABLE) or {}
    table = [f"[{FEATURES_TABLE}]"] + [f"{key} = {toml_value(value)}" for key, value in sorted(features.items())] if features else []
    return top, table


def render_codex_agent(text, file_name, extra=None):
    """The TOML of the native Codex subagent of one subagent template (``file_name`` is agents/<file>);
    ``extra`` is what its access and model-tier map to in Codex (model_reasoning_effort, features)."""
    fields, body = split_subagent(text, f"agents/{file_name}")
    expected_name = file_name[:-len(MARKDOWN_SUFFIX)]
    if fields["name"] != expected_name:
        raise ProfileError(f"agents/{file_name}: the subagent is named '{fields['name']}'; it must be "
                           f"'{expected_name}', the name of its file, so Codex and Claude Code call it the same")
    top, table = metadata_lines(extra or {})
    return (GENERATED_HEADER.format(file=file_name)
            + f"name = {toml_basic_string(fields['name'])}\n"
            + f"description = {toml_basic_string(fields['description'])}\n"
            + "".join(f"{line}\n" for line in top)
            + f"developer_instructions = {toml_multiline_string(body)}\n"
            + ("\n" + "\n".join(table) + "\n" if table else ""))


def render_codex_agent_file(source_path, file_name, skill_dir=None):
    """render_codex_agent of a template on disk; ``file_name`` is its name under agents/ (the text of a
    workspace-scoped subagent lives in the cache under its sha256). With ``skill_dir`` its access and
    model-tier map to Codex through assets/providers.json."""
    with open(source_path, encoding="utf-8", newline="") as template_file:
        text = template_file.read()
    extra = {}
    if skill_dir:
        import agent_ready_agent_metadata as agent_metadata
        declared = agent_metadata.metadata(text, f"agents/{file_name}")
        extra = agent_metadata.view_fields(skill_dir, agent_metadata.VIEW_CODEX, declared) if declared else {}
    return render_codex_agent(text, file_name, extra)
